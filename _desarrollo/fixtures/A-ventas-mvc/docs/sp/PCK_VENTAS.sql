-- Fuente extraida de produccion (Oracle 10g) solo para analisis.
-- Este archivo NO se ejecuta ni se referencia desde la API.
CREATE OR REPLACE PACKAGE PCK_VENTAS AS
  PROCEDURE SP_LISTAR_VENTAS(pDesde DATE, pHasta DATE, pCursor OUT SYS_REFCURSOR);
  PROCEDURE SP_OBTENER_VENTA(pIdVenta NUMBER, pCursor OUT SYS_REFCURSOR);
  PROCEDURE SP_REGISTRAR_VENTA(pFolio VARCHAR2, pIdCliente NUMBER, pMonto NUMBER, pFecha DATE);
  PROCEDURE SP_ANULAR_VENTA(pIdVenta NUMBER);
  PROCEDURE SP_CERRAR_CAJA(pIdCaja NUMBER);
  FUNCTION FN_TOTAL_VENTA(pIdVenta NUMBER) RETURN NUMBER;
  FUNCTION FN_SIGUIENTE_FOLIO(pSerie VARCHAR2) RETURN VARCHAR2;
END PCK_VENTAS;
/

CREATE OR REPLACE PACKAGE BODY PCK_VENTAS AS

  PROCEDURE SP_LISTAR_VENTAS(pDesde DATE, pHasta DATE, pCursor OUT SYS_REFCURSOR) IS
  BEGIN
    OPEN pCursor FOR
      SELECT v.ID_VENTA, v.FOLIO, v.FECHA, PCK_VENTAS.FN_TOTAL_VENTA(v.ID_VENTA) AS MONTO_TOTAL
        FROM VENTAS v
       WHERE v.FECHA BETWEEN pDesde AND pHasta
         AND v.ORIGEN <> 'PCK_VENTAS.SP_IMPORTAR_VENTAS';
  END SP_LISTAR_VENTAS;

  PROCEDURE SP_ANULAR_VENTA(pIdVenta NUMBER) IS
  BEGIN
    UPDATE VENTAS SET ESTADO = 'ANULADA' WHERE ID_VENTA = pIdVenta;
    PCK_AUDITORIA.SP_REGISTRAR_CAMBIO(pIdVenta, 'VENTAS', USER);
  END SP_ANULAR_VENTA;

  PROCEDURE SP_CERRAR_CAJA(pIdCaja NUMBER) IS
  BEGIN
    PCK_CAJA.SP_CUADRAR(pIdCaja);
  END SP_CERRAR_CAJA;

  FUNCTION FN_TOTAL_VENTA(pIdVenta NUMBER) RETURN NUMBER IS
    vTotal NUMBER;
  BEGIN
    SELECT SUM(d.CANTIDAD * d.PRECIO) + PCK_IMPUESTOS.FN_IVA(pIdVenta)
      INTO vTotal
      FROM VENTAS_DETALLE d
     WHERE d.ID_VENTA = pIdVenta;
    RETURN vTotal;
  END FN_TOTAL_VENTA;

  FUNCTION FN_SIGUIENTE_FOLIO(pSerie VARCHAR2) RETURN VARCHAR2 IS
  BEGIN
    RETURN pSerie || '-' || LPAD(SEQ_FOLIO.NEXTVAL, 8, '0');
  END FN_SIGUIENTE_FOLIO;

END PCK_VENTAS;
/
