-- Extracto del cuerpo del paquete (solo referencia para el equipo de migracion)
CREATE OR REPLACE PACKAGE BODY PCK_INVENTARIO AS

  PROCEDURE SP_LISTAR_PRODUCTOS(p_texto IN VARCHAR2, p_cur OUT SYS_REFCURSOR) IS
  BEGIN
    OPEN p_cur FOR
      SELECT p.ID, p.SKU, PCK_UTIL.FN_UNIDAD_MEDIDA(p.UNIDAD_BASE) AS UNIDAD
        FROM PRODUCTOS p
       WHERE p.ESTADO = 'A';
  END SP_LISTAR_PRODUCTOS;

  PROCEDURE SP_TRANSFERIR_STOCK(p_origen IN VARCHAR2, p_destino IN VARCHAR2, p_producto IN VARCHAR2, p_cantidad IN NUMBER) IS
  BEGIN
    PCK_ALMACEN.SP_RESERVAR_STOCK(p_origen, p_producto, p_cantidad);
    SP_AJUSTAR_STOCK(p_producto, -p_cantidad, 'TRANSFERENCIA', NULL);
  END SP_TRANSFERIR_STOCK;

END PCK_INVENTARIO;
/
