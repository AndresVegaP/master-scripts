CREATE OR REPLACE PACKAGE BODY PCK_CLIENTES AS

  PROCEDURE SP_OBTENER_CLIENTE(p_id_cliente IN NUMBER, p_cursor OUT SYS_REFCURSOR) IS
  BEGIN
    OPEN p_cursor FOR
      SELECT ID_CLIENTE, NOMBRE, EMAIL, PCK_UTIL.FN_FORMATEAR_RUT(RUT) AS RUT
        FROM CLIENTES
       WHERE ID_CLIENTE = p_id_cliente;
  END SP_OBTENER_CLIENTE;

  PROCEDURE SP_ACTUALIZAR(p_id_cliente IN NUMBER, p_nombre IN VARCHAR2, p_email IN VARCHAR2) IS
  BEGIN
    UPDATE CLIENTES SET NOMBRE = p_nombre, EMAIL = p_email WHERE ID_CLIENTE = p_id_cliente;
    PCK_AUDITORIA.SP_REGISTRAR_ACCESO('ACTUALIZAR', p_id_cliente, USER);
    COMMIT;
  END SP_ACTUALIZAR;

END PCK_CLIENTES;
/
